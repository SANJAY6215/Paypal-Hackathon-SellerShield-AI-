/**
 * Defence-as-Pull-Request. Turns a human-approved, test-verified defence into a DRAFT GitHub pull request containing:
 *  - the unified diff (sellershield/fixes/<fix>.patch)
 *  - a runnable regression test (sellershield/regression/<fix>.test.ts)
 *  - a report with the before/after attack proof (sellershield/reports/<fix>.md)
 * It never merges anything, never pushes to the base branch, and the repo owner decides whether to merge.
 */
export interface PrInput {
  defence: { id: string; fixId: string; proposedFix: string; patch: string; explanation: string; tradeoffs: unknown; approvedAt: Date | null; status: string };
  vulnerability: { testCaseId: string; title: string; severity: string; rootCause: string; exposure: any; reproductionSteps?: unknown; evidence?: unknown; description?: string };
  tests: { testName: string; kind: string; status: string; actualResult: string }[];
  approver: string;
  merchantName: string;
}
export interface PrPackage { branch: string; title: string; body: string; files: { path: string; content: string }[]; base: string; repo: string }

export function buildPrPackage(i: PrInput, repo: string, base: string): PrPackage {
  const { defence: d, vulnerability: v } = i;
  const fix = d.fixId;
  const passed = i.tests.filter((t) => t.status === 'passed').length;
  const test = `// Generated by SellerShield AI for ${v.testCaseId} (${fix}). Safe to run: pure simulation, no network.
import { describe, it, expect } from 'vitest';
import { scenarioById } from '../../backend/src/simulator/scenarios';

describe('SellerShield regression: ${v.testCaseId} / ${fix}', () => {
  const sc = scenarioById('${v.testCaseId}')!;
  it('the attack reproduces on the vulnerable implementation (control)', () => {
    expect(sc.reproduce(new Set()).exploited).toBe(true);
  });
  it('the attack is blocked once the fix is applied', () => {
    expect(sc.reproduce(new Set(['${fix}'] as any)).exploited).toBe(false);
  });
});
`;
  const exp = v.exposure;
  const report = `# ${v.testCaseId}: ${v.title}

Severity: **${v.severity}** · Fix: \`${fix}\` · Approved by: ${i.approver}${d.approvedAt ? ' on ' + d.approvedAt.toISOString() : ''}

## Description
${v.description ?? v.title}

## Attack reproduction (simulated NovaCart shop)
${(Array.isArray(v.reproductionSteps) ? (v.reproductionSteps as string[]) : []).map((x, n) => `${n + 1}. ${x}`).join('\n') || '(see evidence)'}

Evidence from the original run:
${(Array.isArray(v.evidence) ? (v.evidence as any[]) : []).map((e) => `- step ${e.n}: ${e.action} -> expected "${e.expected}", actual "${e.actual}"`).join('\n')}

## Root cause
${v.rootCause}

## What the fix does
${d.explanation}

## Before / after (SellerShield simulator - not a real-world attack)
${i.tests.map((t) => `- [${t.status}] ${t.testName}: ${t.actualResult}`).join('\n') || '- (no tests recorded)'}

${exp ? `## Simulated exposure\n$${exp.perAttack} excess per simulated attack; annual projection $${exp.exposure.low} / $${exp.exposure.expected} / $${exp.exposure.high} (low / expected / high). **Simulated projection, not an actual loss.**\n` : ''}
## Security impact
Removes the demonstrated loss path for this weakness in the simulated shop. Severity: ${v.severity}. Figures are simulated projections, not actual losses.

## Remaining limitations
- Verified only against the SellerShield simulator, not against a production system.
- This PR adds the patch, a regression test and evidence; it does not itself change application code.
- Other weaknesses and attack chains are unaffected unless they share this root cause.

## Trade-offs
${(Array.isArray(d.tradeoffs) ? d.tradeoffs : []).map((t) => `- ${t}`).join('\n')}
`;
  const body = `## SellerShield AI - verified defence for \`${v.testCaseId}\`

**${v.title}** (${v.severity}) on **${i.merchantName}**

${d.proposedFix}

### Verification (all executed by SellerShield before this PR was opened)
- ${passed}/${i.tests.length} regression checks passed: original attack blocked, legitimate operations still work, no new exploit in other scenarios.
- Human approval: ${i.approver}.

### Reproduction
${(Array.isArray(v.reproductionSteps) ? (v.reproductionSteps as string[]) : []).map((x, n) => `${n + 1}. ${x}`).join('\n')}

### Root cause
${v.rootCause}

### Files
- \`sellershield/fixes/${fix}.patch\` - unified diff of the vulnerable → secure rule
- \`sellershield/regression/${fix}.test.ts\` - runnable regression test
- \`sellershield/reports/${fix}.md\` - evidence and trade-offs

> Draft PR generated by SellerShield AI. It does **not** change application code by itself; review the patch, run the regression test, and merge only if you agree. All dollar figures are simulated projections.
`;
  return {
    repo, base,
    branch: `sellershield/${fix}-${Date.now().toString(36)}`,
    title: `SellerShield: fix ${v.testCaseId} - ${d.proposedFix.split(':')[0].slice(0, 70)}`,
    body,
    files: [
      { path: `sellershield/fixes/${fix}.patch`, content: d.patch },
      { path: `sellershield/regression/${fix}.test.ts`, content: test },
      { path: `sellershield/reports/${fix}.md`, content: report },
    ],
  };
}

export function githubConfigured() { return !!(env.githubToken && env.githubRepo); }
const REPO_RE = /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/;

async function gh(method: string, path: string, body?: unknown, fetchImpl: typeof fetch = fetch) {
  const res = await fetchImpl(env.githubApi.replace(/\/$/, '') + path, {
    method,
    headers: { authorization: `Bearer ${env.githubToken}`, accept: 'application/vnd.github+json', 'x-github-api-version': '2022-11-28', 'content-type': 'application/json', 'user-agent': 'SellerShieldAI' },
    body: body ? JSON.stringify(body) : undefined,
  });
  const json: any = await res.json().catch(() => ({}));
  if (!res.ok) throw Object.assign(new Error(redact(`GitHub ${method} ${path.replace(/\/contents\/.*/, '/contents/…')} failed: HTTP ${res.status} ${json?.message ?? ''}`).replaceAll(env.githubToken || '\u0000', '[token]')), { status: 502 });
  return json;
}

export async function openPullRequest(pkg: PrPackage, fetchImpl: typeof fetch = fetch): Promise<{ url: string; number: number; branch: string; draft: boolean }> {
  if (!env.githubToken) throw Object.assign(new Error('GITHUB_TOKEN is not configured'), { status: 422 });
  if (!REPO_RE.test(pkg.repo)) throw Object.assign(new Error('GITHUB_REPO must look like owner/name'), { status: 422 });
  const ref = await gh('GET', `/repos/${pkg.repo}/git/ref/heads/${encodeURIComponent(pkg.base)}`, undefined, fetchImpl);
  await gh('POST', `/repos/${pkg.repo}/git/refs`, { ref: `refs/heads/${pkg.branch}`, sha: ref.object.sha }, fetchImpl);
  for (const f of pkg.files) {
    await gh('PUT', `/repos/${pkg.repo}/contents/${f.path}`, { message: `SellerShield: add ${f.path}`, content: Buffer.from(f.content, 'utf8').toString('base64'), branch: pkg.branch }, fetchImpl);
  }
  const pr = await gh('POST', `/repos/${pkg.repo}/pulls`, { title: pkg.title, head: pkg.branch, base: pkg.base, body: pkg.body, draft: true }, fetchImpl);
  return { url: pr.html_url, number: pr.number, branch: pkg.branch, draft: true };
}

export interface PrVerification { ok: boolean; checks: { name: string; ok: boolean; detail: string }[]; number: number; url: string; repo: string; head: string; base: string; draft: boolean; filesChanged: string[] }

/** Independently re-read the PR from GitHub and verify it is what we claim (draft, right branches, expected files, test present). */
export async function verifyPullRequest(pkg: PrPackage, number: number, fetchImpl: typeof fetch = fetch): Promise<PrVerification> {
  const pr = await gh('GET', `/repos/${pkg.repo}/pulls/${number}`, undefined, fetchImpl);
  const files: any[] = await gh('GET', `/repos/${pkg.repo}/pulls/${number}/files`, undefined, fetchImpl);
  const names = (Array.isArray(files) ? files : []).map((f) => String(f.filename));
  const expected = pkg.files.map((f) => f.path);
  const checks = [
    { name: 'PR is a draft', ok: pr.draft === true, detail: `draft=${pr.draft}` },
    { name: 'Source branch is the new feature branch', ok: pr.head?.ref === pkg.branch, detail: `head=${pr.head?.ref}` },
    { name: 'Target is the configured base branch', ok: pr.base?.ref === pkg.base, detail: `base=${pr.base?.ref}` },
    { name: 'Source branch is not the base branch', ok: pr.head?.ref !== pr.base?.ref, detail: '' },
    { name: 'Exactly the expected files changed', ok: expected.every((e) => names.includes(e)) && names.length === expected.length, detail: names.join(', ') },
    { name: 'Regression test included', ok: names.some((n) => /regression\/.+\.test\.ts$/.test(n)), detail: '' },
    { name: 'PR is not merged', ok: pr.merged !== true && pr.state === 'open', detail: `state=${pr.state} merged=${pr.merged}` },
  ];
  return { ok: checks.every((c) => c.ok), checks, number, url: pr.html_url, repo: pkg.repo, head: pr.head?.ref, base: pr.base?.ref, draft: pr.draft === true, filesChanged: names };
}

/** Read-only pre-flight: can the configured token reach the repo, does it have push access, does the base branch exist? Never writes. */
export async function githubPreflight(fetchImpl: typeof fetch = fetch) {
  if (!githubConfigured()) return { configured: false, reason: !env.githubToken ? 'GITHUB_TOKEN is not set' : 'GITHUB_REPO is not set (use a dedicated test repository)' };
  if (!REPO_RE.test(env.githubRepo)) return { configured: false, reason: 'GITHUB_REPO must look like owner/name' };
  try {
    const repo = await gh('GET', `/repos/${env.githubRepo}`, undefined, fetchImpl);
    const base = await gh('GET', `/repos/${env.githubRepo}/branches/${encodeURIComponent(env.githubBase)}`, undefined, fetchImpl).then(() => true, () => false);
    return { configured: true, repo: repo.full_name, private: !!repo.private, canPush: !!repo.permissions?.push, defaultBranch: repo.default_branch, baseBranch: env.githubBase, baseBranchExists: base, ok: !!repo.permissions?.push && base };
  } catch (e: any) { return { configured: true, ok: false, error: e.message }; }
}
